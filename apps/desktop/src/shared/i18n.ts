export type Language = "en" | "it";
const dictionaries: Record<Language, Record<MessageKey, string>> = { en, it };

/** Picks Italian for any Italian locale and English for everything else. */
export function languageFrom(locale: string | undefined): Language {
  return locale?.toLowerCase().startsWith("it") ? "it" : "en";
}

export function translate(lang: Language, key: MessageKey, vars: Record<string, string> = {}): string {
  const text = dictionaries[lang][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? `{${name}}`);
}

/** The greeting for the hour of the day: morning from 5 to 12, afternoon until 18, evening through the night. */

/** The greeting for the hour: evening until five in the morning, so midnight isn't "good morning". */
export function greeting(lang: Language, hour: number, name: string): string {
  const part = hour < 5 || hour >= 18 ? "evening" : hour < 12 ? "morning" : "afternoon";
  return GREETINGS[lang][part].replace("{name}", name);
}

/** The line under the greeting: the first-task line, or the one at `pick` (from 0 up to 1) in the language's list. */
export function homeLine(lang: Language, pick: number, firstTask = false): string {
  if (firstTask) return FIRST_TASK[lang];
  const lines = LINES[lang];
  return lines[Math.min(lines.length - 1, Math.floor(pick * lines.length))] ?? "";
}

/**
 * What the app shows for a built-in guide in `lang` (title, description and steps), or null to show the guide's own
 * English file text, as for English and for a guide with no translation. Only what is shown changes: the guide's
 * folder name and file stay as they are.
 */
export function guideText(lang: Language, name: string): GuideIt | null {
  return lang === "it" && Object.hasOwn(GUIDES_IT, name) ? (GUIDES_IT[name] ?? null) : null;
}
